
'''
Data Types:
- Integers
- Floats
- Strings
- Booleans
- None

Type Checking:
- type()

Type Conversion:
- int()
- float()
- str()
'''

# Integers

age = 25
print(type(age))  # Output: <class 'int'>
print(str(age))  # Output: 25
print(float(age)) # Output: 25.0
print(bool(age)) # Output: True

# Floats
price = 9.99
print(type(price))  # Output: <class 'float'>

# Strings
name = "Alice"
print(type(name))  # Output: <class 'str'>

# Booleans
is_student = True
print(type(is_student))  # Output: <class 'bool'>

# None
result = None
print(type(result))  # Output: <class 'NoneType'>